import { mkdir, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { rolldown } from 'rolldown'

// Bundles the Edge Functions: `compose` (server/edge/entry.ts and everything it imports: the composer, its rules, the Zod schemas, the Gemini
// caller) and `delete-account` (server/edge/deleteAccountEntry.ts), each into one self-contained file, since the Supabase deploy only takes what
// is inside supabase/functions. The one source of truth is the app's own code, so a function and the app can never disagree.
//
//   npm run build:edge                  writes supabase/functions/compose/index.ts and supabase/functions/delete-account/index.ts (git-ignored)
//   npm run deploy:compose              builds, then deploys compose (see docs/deploy.md)
//   npm run deploy:delete-account       builds, then deploys delete-account

const root = fileURLToPath(new URL('..', import.meta.url))

// Each function: its entry file in server/edge, and where the bundle goes.
export const FUNCTIONS = {
  compose: { entry: 'server/edge/entry.ts' },
  'delete-account': { entry: 'server/edge/deleteAccountEntry.ts' },
}
const outFileOf = (name) => `${root}supabase/functions/${name}/index.ts`
export const DEFAULT_OUT = outFileOf('compose')

export async function buildEdge(outFile = DEFAULT_OUT, name = 'compose') {
  const { entry } = FUNCTIONS[name]
  const bundle = await rolldown({ input: `${root}${entry}`, platform: 'neutral', treeshake: true, logLevel: 'warn' })
  try {
    const { output } = await bundle.generate({ format: 'esm', codeSplitting: false })
    const code = output.find((chunk) => chunk.type === 'chunk')?.code ?? ''
    const banner = `// Generated by \`npm run build:edge\` from ${entry}. Do not edit: change the source and build again.\n// deno-lint-ignore-file\n// @ts-nocheck\n`
    await mkdir(dirname(outFile), { recursive: true })
    await writeFile(outFile, banner + code)
    return { outFile, bytes: Buffer.byteLength(banner + code) }
  } finally {
    await bundle.close()
  }
}

// Run directly: build every function, or only the one named, to its default place.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const wanted = process.argv[2]
  if (wanted && !(wanted in FUNCTIONS)) throw new Error(`Unknown function "${wanted}". Use ${Object.keys(FUNCTIONS).join(' or ')}.`)
  for (const name of wanted ? [wanted] : Object.keys(FUNCTIONS)) {
    const { outFile, bytes } = await buildEdge(outFileOf(name), name)
    console.log(`Built ${outFile} (${Math.round(bytes / 1024)} KB)`)
  }
}
