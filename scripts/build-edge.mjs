import { mkdir, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { rolldown } from 'rolldown'

// Bundles the `compose` Edge Function: server/edge/entry.ts and everything it imports (the composer, its rules, the Zod schemas, the Gemini
// caller) into one self-contained file, since the Supabase deploy only takes what is inside supabase/functions. The one source of truth is the
// app's own code, so the function and the app can never disagree about what a valid turn is.
//
//   npm run build:edge        writes supabase/functions/compose/index.ts (git-ignored)
//   npm run deploy:compose    builds, then deploys it (see docs/deploy.md)

const root = fileURLToPath(new URL('..', import.meta.url))
export const DEFAULT_OUT = `${root}supabase/functions/compose/index.ts`

export async function buildEdge(outFile = DEFAULT_OUT) {
  const bundle = await rolldown({ input: `${root}server/edge/entry.ts`, platform: 'neutral', treeshake: true, logLevel: 'warn' })
  try {
    const { output } = await bundle.generate({ format: 'esm', codeSplitting: false })
    const code = output.find((chunk) => chunk.type === 'chunk')?.code ?? ''
    const banner = '// Generated by `npm run build:edge` from server/edge/entry.ts. Do not edit: change the source and build again.\n// deno-lint-ignore-file\n// @ts-nocheck\n'
    await mkdir(dirname(outFile), { recursive: true })
    await writeFile(outFile, banner + code)
    return { outFile, bytes: Buffer.byteLength(banner + code) }
  } finally {
    await bundle.close()
  }
}

// Run directly: build to the default place.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { outFile, bytes } = await buildEdge(process.argv[2])
  console.log(`Built ${outFile} (${Math.round(bytes / 1024)} KB)`)
}
