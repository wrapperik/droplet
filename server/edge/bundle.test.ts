// @vitest-environment node
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { validOpenReply } from '../../src/compose/fixtures.ts'
// @ts-expect-error the build script is plain JavaScript
import { buildEdge } from '../../scripts/build-edge.mjs'

// The function as it is deployed: the one file `npm run build:edge` makes. It is built here into a temporary folder and run, with a stand-in for
// Deno and for Supabase, so a change that works in the source but breaks the bundle (a Node-only import, a missing dependency) is caught.
let dir = ''
let file = ''
let code = ''

beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), 'droplet-edge-'))
  file = join(dir, 'index.mjs')
  await buildEdge(file)
  code = await readFile(file, 'utf8')
}, 60_000)
afterAll(() => rm(dir, { recursive: true, force: true }))

describe('the bundled Edge Function', () => {
  it('is one self-contained file that needs nothing from Node, from the app or from node_modules', () => {
    expect(code).not.toMatch(/from ['"]node:/)
    expect(code).not.toMatch(/require\(/)
    expect(code).not.toMatch(/\bprocess\.(env|argv|cwd)/)
    // everything it imports is inside it: no import of a package or a file
    expect(code).not.toMatch(/^import .* from ['"][^'"]+['"]/m)
    expect(code).toMatch(/Deno\.serve\(/)
  })

  it('carries a banner that says it is generated, so nobody edits it by hand', () => {
    expect(code.startsWith('// Generated by `npm run build:edge`')).toBe(true)
  })

  it('does not contain a key, a URL of the project or anything of this machine\'s', () => {
    expect(code).not.toMatch(/sb_secret_|sb_publishable_|eyJhbGciOi/)
    expect(code).not.toContain('/Users/')
  })

  it('serves: refuses a request with no token, and answers a signed-in founder, with the key from the function\'s own environment', async () => {
    let handler: ((request: Request) => Promise<Response>) | null = null
    const g = globalThis as unknown as { Deno?: unknown; fetch: typeof fetch }
    const realFetch = g.fetch
    const seenModelKeys: string[] = []
    g.Deno = {
      env: { toObject: () => ({ SUPABASE_URL: 'https://abc.supabase.co', SUPABASE_SERVICE_ROLE_KEY: 'service-key', GEMINI_API_KEY: 'gemini-secret', COMPOSE_LIMIT_PER_HOUR: '5' }) },
      serve: (given: (request: Request) => Promise<Response>) => {
        handler = given
      },
    }
    g.fetch = (async (url: string, init?: RequestInit) => {
      if (url.includes('/auth/v1/user')) return new Response(JSON.stringify({ id: 'user-1' }), { status: 200 })
      if (url.includes('/rest/v1/compositions') && init?.method === 'POST') return new Response(null, { status: 201 })
      if (url.includes('/rest/v1/compositions')) return new Response('[]', { status: 200, headers: { 'content-range': '*/0' } })
      if (url.includes('generativelanguage.googleapis.com')) {
        const sent = init?.headers as Record<string, string> | undefined
        seenModelKeys.push(String(sent?.['x-goog-api-key']))
        return new Response(JSON.stringify({ candidates: [{ content: { parts: [{ text: validOpenReply }] }, finishReason: 'STOP' }] }), { status: 200 })
      }
      throw new Error(`unexpected ${url}`)
    }) as unknown as typeof fetch
    try {
      await import(/* @vite-ignore */ pathToFileURL(file).href)
      expect(handler).not.toBeNull()
      const serve = handler as unknown as (request: Request) => Promise<Response>
      const post = (headers: Record<string, string>) => serve(new Request('https://f.example/compose', { method: 'POST', headers: { 'content-type': 'application/json', ...headers }, body: JSON.stringify({ intent: 'a colour palette for my gift box business' }) }))
      expect((await post({})).status).toBe(401)
      const ok = await post({ authorization: 'Bearer the-token' })
      expect(ok.status).toBe(200)
      expect(await ok.json()).toMatchObject({ outcome: 'valid', turn: { task: 'brand' } })
      expect(seenModelKeys).toEqual(['gemini-secret'])
    } finally {
      g.fetch = realFetch
      delete g.Deno
    }
  }, 30_000)
})
