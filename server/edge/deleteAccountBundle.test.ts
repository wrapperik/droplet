// @vitest-environment node
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
// @ts-expect-error the build script is plain JavaScript
import { buildEdge } from '../../scripts/build-edge.mjs'

// The delete-account function as it is deployed: built here into a temporary folder and run, with a stand-in for Deno and for Supabase, so a
// change that works in the source but breaks the bundle (a Node-only import, a missing dependency) is caught.
let dir = ''
let file = ''
let code = ''

beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), 'droplet-edge-delete-'))
  file = join(dir, 'index.mjs')
  await buildEdge(file, 'delete-account')
  code = await readFile(file, 'utf8')
}, 60_000)
afterAll(() => rm(dir, { recursive: true, force: true }))

describe('the bundled delete-account function', () => {
  it('is one self-contained file that needs nothing from Node, from the app or from node_modules', () => {
    expect(code).not.toMatch(/from ['"]node:/)
    expect(code).not.toMatch(/require\(/)
    expect(code).not.toMatch(/\bprocess\.(env|argv|cwd)/)
    expect(code).not.toMatch(/^import .* from ['"][^'"]+['"]/m)
    expect(code).toMatch(/Deno\.serve\(/)
  })

  it('carries a banner that says it is generated, and names its own entry', () => {
    expect(code.startsWith('// Generated by `npm run build:edge` from server/edge/deleteAccountEntry.ts')).toBe(true)
  })

  it('holds no key, no model code and nothing of this machine\'s', () => {
    expect(code).not.toMatch(/sb_secret_|sb_publishable_|eyJhbGciOi/)
    expect(code).not.toContain('/Users/')
    expect(code).not.toMatch(/generativelanguage|GEMINI/)
  })

  it('serves: refuses a request with no valid token, and deletes the founder whose token it is, with the key from its own environment', async () => {
    let handler: ((request: Request) => Promise<Response>) | null = null
    const g = globalThis as unknown as { Deno?: unknown; fetch: typeof fetch }
    const realFetch = g.fetch
    const seen: { url: string; method: string; key: string }[] = []
    g.Deno = {
      env: { toObject: () => ({ SUPABASE_URL: 'https://abc.supabase.co', SUPABASE_SERVICE_ROLE_KEY: 'service-key' }) },
      serve: (given: (request: Request) => Promise<Response>) => {
        handler = given
      },
    }
    g.fetch = (async (url: string, init?: RequestInit) => {
      const headers = (init?.headers ?? {}) as Record<string, string>
      seen.push({ url, method: init?.method ?? 'GET', key: headers.apikey })
      if (url.endsWith('/auth/v1/user')) return headers.authorization === 'Bearer the-token' ? new Response(JSON.stringify({ id: 'user-1' }), { status: 200 }) : new Response('{}', { status: 401 })
      if (url.endsWith('/auth/v1/admin/users/user-1') && init?.method === 'DELETE') return new Response('{}', { status: 200 })
      throw new Error(`unexpected ${url}`)
    }) as unknown as typeof fetch
    try {
      await import(/* @vite-ignore */ pathToFileURL(file).href)
      expect(handler).not.toBeNull()
      const serve = handler as unknown as (request: Request) => Promise<Response>
      const post = (headers: Record<string, string>) => serve(new Request('https://f.example/delete-account', { method: 'POST', headers }))
      expect((await post({})).status).toBe(401)
      expect((await post({ authorization: 'Bearer forged' })).status).toBe(401)
      expect(seen.some((call) => call.method === 'DELETE')).toBe(false)
      const ok = await post({ authorization: 'Bearer the-token' })
      expect(ok.status).toBe(200)
      expect(await ok.json()).toEqual({ deleted: true })
      expect(seen.filter((call) => call.method === 'DELETE')).toEqual([{ url: 'https://abc.supabase.co/auth/v1/admin/users/user-1', method: 'DELETE', key: 'service-key' }])
    } finally {
      g.fetch = realFetch
      delete g.Deno
    }
  }, 30_000)
})
